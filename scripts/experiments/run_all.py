"""Reproduce every number and figure in the report with one command (Role 6).

    python scripts/experiments/run_all.py            # full run, ~35 min on a laptop
    python scripts/experiments/run_all.py --quick    # fewer seeds, for a smoke test

Fits every implemented detector once per temporal fold, then runs
  1. magnitude_sweep  - AUC vs magnitude {1,2,3,4,6}
  2. repeated_cv      - 10 injection seeds at magnitude 4, CIs, paired tests vs k-sigma
  3. hard_variants    - AUC per anomaly kind, anywhere vs quiet-period placement
  4. ablation         - Stage C drop-one-feature ablation + random-neighbour control
and writes CSVs and PNGs to results/experiments/ and the summary that the
slides and the report quote to results/RESULTS.md. Detectors or Stage C code
that are still stubs are skipped and marked as pending in RESULTS.md.
"""

from __future__ import annotations

import argparse
import json
import time
from datetime import datetime

import numpy as np
import pandas as pd

import ablation
import common as C
import hard_variants
import magnitude_sweep
import repeated_cv
from signoise.config import RESULTS_DIR


def _table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(v) for v in r.values) + " |")
    return "\n".join(lines)


def _pm(m, s):
    return f"{m:.3f} ± {s:.3f}"


def _ci(lo, hi):
    return f"[{max(lo, 0):.3f}, {min(hi, 1):.3f}]"


def _p(p):
    return "<0.001" if p < 1e-3 else f"{p:.3f}"


def _rel(path):
    """Figure path relative to the folder RESULTS.md is written to."""
    return path.relative_to(C.OUT.parent).as_posix()


def write_results(meta, cv_summ, cv_comp, sweep, variants, abl) -> str:
    L = C.LABELS
    out = [f"# Results\n",
           f"Generated by `python scripts/experiments/run_all.py` on {meta['when']} "
           f"in {meta['minutes']:.0f} min. Do not edit by hand; re-run the script.\n",
           "## Setting\n",
           f"- Data: Intel Berkeley Lab, {meta['shape'][1]} nodes, {meta['shape'][0]} steps of "
           f"{C.DEFAULTS['bin_epochs']} epochs (~5 min), before {C.DEFAULTS['end']}; "
           f"{meta['missing']:.1%} of cells missing (forward-filled within each window).",
           f"- {C.DEFAULTS['n_folds']} contiguous temporal folds, {C.DEFAULTS['gap']}-step gap on "
           "each side of the test block; everything is fitted on the training window only.",
           "- Detectors see temperature, humidity and light (robust z-scores); scored cells are "
           "observed and not real anomalies.",
           f"- Injected per test fold: {C.DEFAULTS['n_events']} events + "
           f"{C.DEFAULTS['n_failures']} failures, magnitude {C.DEFAULTS['magnitude']:g} "
           "training SDs, unless stated.",
           f"- Detectors: {', '.join(L[d] for d in meta['detectors'])}."
           + (f" Pending (not implemented yet): {', '.join(meta['pending'])}."
              if meta["pending"] else ""),
           "- Uncertainty: runs in the same fold share data, so 95% CIs and paired tests use "
           "the fold means (n = 5, t-distribution); run-level wins are descriptive.\n"]

    out.append("## 1. Detection, repeated temporal CV\n")
    out.append(f"{meta['cv_seeds']} injection seeds x {C.DEFAULTS['n_folds']} folds. "
               "Mean ± std over runs; 95% CI over fold means.\n")
    rows = []
    for _, r in cv_summ.iterrows():
        rows.append({"detector": L[r.detector],
                     "AUC": _pm(r.auc_mean, r.auc_std),
                     "AUC 95% CI": _ci(r.auc_ci_lo, r.auc_ci_hi),
                     "AUC events": _pm(r.auc_event_mean, r.auc_event_std),
                     "AUC failures": _pm(r.auc_failure_mean, r.auc_failure_std),
                     "precision@k": _pm(r.precision_at_k_mean, r.precision_at_k_std)})
    out.append(_table(pd.DataFrame(rows)) + "\n")
    out.append("**Paired comparison with the k-sigma baseline** (difference of fold means; "
               "p from a paired t-test, n = 5; the exact sign-flip test cannot go below "
               "0.0625 with 5 folds, so a fold count of 5/5 is the strongest it can show).\n")
    rows = []
    for _, r in cv_comp.iterrows():
        rows.append({"detector": L[r.detector], "metric": r.metric,
                     "Δ vs k-sigma": f"{r.mean_diff:+.3f}",
                     "95% CI": f"[{r.ci_lo:+.3f}, {r.ci_hi:+.3f}]", "p (t)": _p(r.p_t),
                     "p (sign-flip)": _p(r.p_perm), "folds better": f"{r.wins}/{r.n}",
                     "runs better": f"{r.run_wins}/{r.n_runs}"})
    out.append(_table(pd.DataFrame(rows)) + "\n")
    out.append(f"![repeated CV]({meta['fig_cv']})\n")

    out.append("## 2. Graded difficulty: AUC vs magnitude\n")
    out.append(f"{meta['sweep_seeds']} seeds per magnitude. Cells: overall AUC "
               "(events / failures).\n")
    piv = []
    for d in [d for d in C.DETECTOR_ORDER if d in set(sweep.detector)]:
        g = sweep[sweep.detector == d].set_index("magnitude")
        row = {"detector": L[d]}
        for m in sorted(sweep.magnitude.unique()):
            row[f"{m:g} SD"] = (f"{g.loc[m, 'auc']:.3f} ({g.loc[m, 'auc_event']:.2f} / "
                                f"{g.loc[m, 'auc_failure']:.2f})")
        piv.append(row)
    out.append(_table(pd.DataFrame(piv)) + "\n")
    out.append(f"![magnitude sweep]({meta['fig_sweep']})\n")

    out.append("## 3. Harder anomaly kinds and quiet-period placement\n")
    out.append(f"Each kind injected alone (20 episodes per fold, magnitude 4), "
               f"{meta['var_seeds']} seeds. AUC of that kind vs normal cells.\n")
    for place in hard_variants.PLACEMENTS:
        s = variants[variants.placement == place]
        piv = []
        for k in hard_variants.KIND_ARGS:
            row = {"kind": hard_variants.KIND_LABELS[k]}
            for d in [d for d in C.DETECTOR_ORDER if d in set(s.detector)]:
                v = s[(s.kind == k) & (s.detector == d)].auc
                row[L[d]] = f"{v.iloc[0]:.3f}" if len(v) else "n/a"
            piv.append(row)
        out.append(f"**Placement: {place}**\n\n" + _table(pd.DataFrame(piv)) + "\n")
    out.append(f"![hard variants]({meta['fig_var']})\n")

    out.append("## 4. Event vs failure: ablation and random-neighbour control\n")
    if abl is None:
        out.append("_Pending: Role 5's Stage C features/classifiers are not on this branch "
                   "yet. Re-run this script after they are merged._\n")
    else:
        summ, figs = abl
        out.append(f"Flags from each detector's top-k cells; classifiers trained on anomalies "
                   f"injected into the training window, tested on the test window. "
                   f"{meta['abl_seeds']} seeds x 5 folds. Balanced accuracy = mean of "
                   "event recall and failure recall. Δ is paired by fold against the full "
                   "model.\n")
        dord = {d: i for i, d in enumerate(meta.get("abl_dets", []))}
        mord = {m: i for i, m in enumerate(ablation.MIXES)}
        keys = sorted(summ[["detector", "mix"]].drop_duplicates().itertuples(index=False),
                      key=lambda k: (dord.get(k[0], 99), mord.get(k[1], 99)))
        for det, mix in keys:
            g = summ[(summ.detector == det) & (summ.mix == mix)]
            rows = []
            for cond in g.condition.unique():
                row = {"condition": cond}
                for cl, nm in (("naive_bayes", "NB"), ("logistic", "LogReg")):
                    r = g[(g.condition == cond) & (g.classifier == cl)]
                    if not len(r):
                        continue
                    r = r.iloc[0]
                    row[f"{nm} acc"] = f"{r.accuracy:.3f}"
                    row[f"{nm} bal. acc"] = f"{r.balanced_accuracy:.3f}"
                    row[f"{nm} Δ bal."] = ("—" if cond == "all features" else
                                           f"{r.delta_balanced:+.3f} (p {_p(r.p_t)})")
                rows.append(row)
            out.append(f"**{L.get(det, det)} flags, {mix} injection**\n\n"
                       + _table(pd.DataFrame(rows)) + "\n")
        for f in figs:
            out.append(f"![{f.stem}]({_rel(f)})\n")

    out.append("## Files\n")
    out.append("All under `results/experiments/`: `*_runs.csv` hold one row per fold x seed "
               "(x detector / condition); the other CSVs are the summaries above.\n")
    return "\n".join(out)


def replot(args) -> None:
    """Figures and RESULTS.md from results/experiments/*.csv (after a full run)."""
    rd = lambda n: pd.read_csv(C.OUT / f"{n}.csv")
    meta = json.loads((C.OUT / "meta.json").read_text())
    meta["shape"] = tuple(meta["shape"])
    cv_runs = rd("repeated_cv_runs")
    cv_summ, cv_comp = repeated_cv.summarise(cv_runs), repeated_cv.paired_vs_baseline(cv_runs)
    sweep, variants = rd("magnitude_sweep"), rd("hard_variants")
    meta.update(fig_cv=_rel(repeated_cv.plot(cv_runs, cv_comp)),
                fig_sweep=_rel(magnitude_sweep.plot(sweep)),
                fig_var=_rel(hard_variants.plot(variants)))
    abl = None
    if (C.OUT / "ablation_runs.csv").exists():
        df = rd("ablation_runs")
        cms = {}
        for k, g in df.groupby(["detector", "mix", "classifier", "condition"]):
            cms[k] = np.array([[g.ee.sum(), g.ef.sum()], [g.fe.sum(), g.ff.sum()]])
        order = ["all features"] + [c for c in df.condition.unique() if c != "all features"]
        summ = ablation.summarise(df)
        figs = [p for d in meta["abl_dets"] for p in ablation.plot(summ, cms, order, d)]
        abl = (summ, figs)
    (RESULTS_DIR / "RESULTS.md").write_text(
        write_results(meta, cv_summ, cv_comp, sweep, variants, abl))
    print("replotted; wrote", RESULTS_DIR / "RESULTS.md")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true",
                    help="1-2 seeds per experiment; writes to results/quick/ instead")
    ap.add_argument("--detectors", nargs="+", default=None)
    ap.add_argument("--ablation-detectors", nargs="+", default=["pca", "ksigma"])
    ap.add_argument("--replot", action="store_true",
                    help="rebuild figures and RESULTS.md from the saved CSVs, no compute")
    args = ap.parse_args()
    if args.replot:
        return replot(args)
    n_sweep, n_cv, n_var, n_abl = (1, 2, 1, 1) if args.quick else (5, 10, 3, 5)
    if args.quick:   # never overwrite the real results with smoke-test numbers
        C.OUT = RESULTS_DIR / "quick" / "experiments"
    t_start = time.time()

    data = C.load()
    print(f"data {data.shape}, missing {data.missing_fraction():.1%}")
    wanted = args.detectors or [d for d in C.DETECTOR_ORDER]
    dets = C.implemented_detectors(wanted)
    pending = [C.LABELS.get(d, d) for d in wanted if d not in dets]
    print("fitting detectors once per fold ...")
    fb = C.FoldBench(data, dets)

    print("[1/4] magnitude sweep")
    sw_runs = magnitude_sweep.run(fb, range(n_sweep))
    C.write_csv(sw_runs, "magnitude_sweep_runs")
    sweep = magnitude_sweep.summarise(sw_runs)
    C.write_csv(sweep, "magnitude_sweep")
    fig_sweep = magnitude_sweep.plot(sweep)

    print("[2/4] repeated CV")
    m4 = sw_runs[sw_runs.magnitude == C.DEFAULTS["magnitude"]].drop(columns="magnitude")
    cv_runs = repeated_cv.run(fb, range(n_cv), reuse=m4)
    C.write_csv(cv_runs, "repeated_cv_runs")
    cv_summ, cv_comp = repeated_cv.summarise(cv_runs), repeated_cv.paired_vs_baseline(cv_runs)
    C.write_csv(cv_summ, "repeated_cv_summary")
    C.write_csv(cv_comp, "repeated_cv_vs_ksigma")
    fig_cv = repeated_cv.plot(cv_runs, cv_comp)

    print("[3/4] harder kinds / quiet placement")
    var_runs = hard_variants.run(fb, range(n_var))
    C.write_csv(var_runs, "hard_variants_runs")
    variants = hard_variants.summarise(var_runs)
    C.write_csv(variants, "hard_variants")
    fig_var = hard_variants.plot(variants)

    print("[4/4] Stage C ablation")
    abl_dets = [d for d in args.ablation_detectors if d in fb.detectors]
    res = ablation.run(fb, abl_dets, range(n_abl))
    abl = None
    if res is not None:
        df, cms, order = res
        C.write_csv(df, "ablation_runs")
        summ = ablation.summarise(df)
        C.write_csv(summ, "ablation")
        figs = [p for d in abl_dets for p in ablation.plot(summ, cms, order, d)]
        abl = (summ, figs)

    meta = dict(when=datetime.now().strftime("%Y-%m-%d %H:%M"),
                minutes=(time.time() - t_start) / 60, shape=data.shape,
                missing=data.missing_fraction(), detectors=dets, pending=pending,
                abl_dets=abl_dets, cv_seeds=n_cv, sweep_seeds=n_sweep, var_seeds=n_var, abl_seeds=n_abl,
                fig_cv=_rel(fig_cv), fig_sweep=_rel(fig_sweep), fig_var=_rel(fig_var))
    (C.OUT / "meta.json").write_text(json.dumps({k: v for k, v in meta.items()
                                                 if not k.startswith("fig")}, default=str))
    md = write_results(meta, cv_summ, cv_comp, sweep, variants, abl)
    path = C.OUT.parent / "RESULTS.md"
    path.write_text(md)
    print(f"\nwrote {path} ({meta['minutes']:.1f} min)")


if __name__ == "__main__":
    main()
